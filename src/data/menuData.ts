export const getMenuById = (id: string): MenuItem | undefined => MENU_LIBRARY.find((item) => item.id === id);

export const getAllIngredients = (): string[] => {
  const ingredients = new Set<string>();
  MENU_LIBRARY.forEach((item) => {
    item.ingredients.forEach((ingredient) => ingredients.add(ingredient));
  });
  return Array.from(ingredients);
};
